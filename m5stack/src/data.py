#   INBOUND (上り 江尾->吉原):  GD10,GD09,GD08,GD07,GD06,GD05,GD04,GD03,GD02,GD01
#   OUTBOUND (下り 吉原->江尾): GD01,GD02,GD03,GD04,GD05,GD06,GD07,GD08,GD09,GD10

def _p(text):
    result = []
    for line in text.strip().split('\n'):
        line = line.strip()
        if not line:
            continue
        row = []
        for t in line.split():
            h, m = t.split(':')
            row.append(int(h) * 60 + int(m))
        result.append(row)
    return result

