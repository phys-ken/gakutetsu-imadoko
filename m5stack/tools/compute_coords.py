# ===== 投影計算 (geometry.js と同じアルゴリズム) =====

def build_projection(track_polyline, stations, screen_w=320, screen_h=240,
                     margin=4, status_bar_h=40):
    map_h = screen_h - status_bar_h
    draw_w = screen_w - 2 * margin
    draw_h = map_h - 2 * margin

    all_lats = [p[0] for p in track_polyline]
    avg_lat_rad = (sum(all_lats) / len(all_lats)) * math.pi / 180
    cos_lat = math.cos(avg_lat_rad)

    def geo_xy(lat, lon):
        return lon * cos_lat, lat

    # bounds: track + stations を含む全点
    all_geo = [geo_xy(p[0], p[1]) for p in track_polyline]
    all_geo += [geo_xy(s["lat"], s["lon"]) for s in stations]

    min_gx = min(p[0] for p in all_geo)
    max_gx = max(p[0] for p in all_geo)
    min_gy = min(p[1] for p in all_geo)
    max_gy = max(p[1] for p in all_geo)

    x_range = max_gx - min_gx
    y_range = max_gy - min_gy
    scale = min(draw_w / x_range, draw_h / y_range)

    offset_x = margin + (draw_w - x_range * scale) / 2
    offset_y = margin + (draw_h - y_range * scale) / 2

    def to_screen(lat, lon):
        gx, gy = geo_xy(lat, lon)
        sx = offset_x + (gx - min_gx) * scale
        sy = offset_y + (max_gy - gy) * scale  # Y 反転
        return round(sx), round(sy)

    return to_screen


def project_onto_segment(px, py, ax, ay, bx, by):
    """点 (px,py) を線分 (ax,ay)-(bx,by) に投影した t ∈ [0,1] を返す。"""
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return 0.0
    t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)
    return max(0.0, min(1.0, t))


def find_station_route_dist(sx, sy, track_px, track_cumlen):
    """駅のスクリーン座標 (sx, sy) から route distance を求める。"""
    best_dist = float('inf')
    best_rd = 0.0
    for j in range(len(track_px) - 1):
        ax, ay = track_px[j]
        bx, by = track_px[j + 1]
        t = project_onto_segment(sx, sy, ax, ay, bx, by)
        proj_x = ax + t * (bx - ax)
        proj_y = ay + t * (by - ay)
        d = math.sqrt((sx - proj_x) ** 2 + (sy - proj_y) ** 2)
        if d < best_dist:
            best_dist = d
            seg_len = track_cumlen[j + 1] - track_cumlen[j]
            best_rd = track_cumlen[j] + t * seg_len
    return best_rd


def generate(out_path):
    to_screen = build_projection(TRACK_POLYLINE, STATIONS)

    track_px = [to_screen(p[0], p[1]) for p in TRACK_POLYLINE]
    station_px = [to_screen(s["lat"], s["lon"]) for s in STATIONS]
    station_km = [s["km"] for s in STATIONS]

    # 累積路線距離 (スクリーンピクセル単位)
    track_cumlen = [0.0]
    for i in range(1, len(track_px)):
        dx = track_px[i][0] - track_px[i - 1][0]
        dy = track_px[i][1] - track_px[i - 1][1]
        track_cumlen.append(track_cumlen[-1] + math.sqrt(dx * dx + dy * dy))

    station_route_dist = [
        find_station_route_dist(sx, sy, track_px, track_cumlen)
        for sx, sy in station_px
    ]

    # デバッグ表示
    print(f"Track points: {len(track_px)}")
    print(f"X range: {min(p[0] for p in track_px)} - {max(p[0] for p in track_px)}")
    print(f"Y range: {min(p[1] for p in track_px)} - {max(p[1] for p in track_px)}")
    print("Station screen positions:")
    for i, s in enumerate(STATIONS):
        sx, sy = station_px[i]
        rd = station_route_dist[i]
        print(f"  {s['name']:10s} km={s['km']:4.1f}  screen=({sx:3d},{sy:3d})  routeDist={rd:.1f}")

    # map_coords.py を書き出す
    lines = [
        "# Auto-generated by tools/compute_coords.py — do not edit manually.",
        "# geometry.js と同じ Mercator 投影で 320x240 (map area 320x200) に変換済み。",
        "",
        "STATION_KM = " + repr(station_km),
        "",
        "STATION_PX = " + repr(station_px),
        "",
        "STATION_ROUTE_DIST = [" + ", ".join(f"{d:.3f}" for d in station_route_dist) + "]",
        "",
        "TRACK_CUMLEN = [" + ", ".join(f"{l:.3f}" for l in track_cumlen) + "]",
        "",
        "TRACK_PX = [",
    ]
    # 8点ずつ1行に
    chunk = 8
    for i in range(0, len(track_px), chunk):
        row = track_px[i:i + chunk]
        lines.append("    " + ", ".join(repr(p) for p in row) + ",")
    lines.append("]")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    script_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(script_dir, "..", "src", "map_coords.py")
    out_path = os.path.normpath(out_path)
    generate(out_path)
